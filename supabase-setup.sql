-- A little sky of our own — private Loy Krathong wishes
-- ก่อนรัน: สร้างผู้ดูแลที่ Supabase > Authentication > Users > Add user
-- คัดลอก UUID ของผู้ดูแล แล้วแทน ADMIN_USER_UUID ด้านล่างด้วย UUID จริง

create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  category text not null check (char_length(category) between 1 and 40),
  message text not null check (char_length(message) between 1 and 500),
  krathong_style text not null default 'lotus'
    check (krathong_style in ('lotus', 'jasmine', 'marigold')),
  created_at timestamptz not null default now()
);

-- รองรับกรณีเคยสร้างตารางจากเวอร์ชันก่อนหน้า
alter table public.wishes add column if not exists krathong_style text not null default 'lotus';

alter table public.wishes enable row level security;

-- ผู้เข้าชมที่ยังไม่ล็อกอินส่งคำอธิษฐานได้เท่านั้น
drop policy if exists "Anyone can submit a wish" on public.wishes;
drop policy if exists "Public can send wishes" on public.wishes;
create policy "Public can send wishes"
on public.wishes for insert
to anon, authenticated
with check (
  char_length(category) between 1 and 40
  and char_length(message) between 1 and 500
  and krathong_style in ('lotus', 'jasmine', 'marigold')
);

-- อ่านได้เฉพาะบัญชีเจ้าของเว็บไซต์ตาม UUID นี้
drop policy if exists "Only owner can read wishes" on public.wishes;
drop policy if exists "Only site owner can read wishes" on public.wishes;
create policy "Only site owner can read wishes"
on public.wishes for select
to authenticated
using ((select auth.uid()) = 'ADMIN_USER_UUID'::uuid);

-- ไม่สร้าง policy สำหรับ update/delete เพื่อไม่เปิดให้แก้ไขหรือลบผ่าน API
grant usage on schema public to anon, authenticated;
revoke all privileges on table public.wishes from anon, authenticated;
grant insert on table public.wishes to anon, authenticated;
grant select on table public.wishes to authenticated;
